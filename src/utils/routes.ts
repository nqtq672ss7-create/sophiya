export function getRouteByPath(pathname: string): SeoRoute {
  const clean = pathname.toLowerCase();
  const found = SEO_ROUTES.find((r) => {
    if (r.path === '/' && (clean === '/' || clean === '')) return true;
    if (r.path !== '/' && (clean === r.path || clean === r.path.replace(/\/$/, '') || clean === r.path.slice(0, -1))) return true;
    return false;
  });
  return found || SEO_ROUTES[0];
}

/**
 * Filter bouquets strictly by route:
 * - On /rozy/: ONLY roses (bouquets with tag or flowerType 'розы', or title containing 'роз')
 * - On /piony/: ONLY peonies
 * - On /hrizantemy/: ONLY chrysanthemums
 * - On /monobukety/: ONLY mono-bouquets
 * - On /avtorskie-bukety/: ONLY author bouquets
 * - On /cvety-v-korobke/: ONLY boxes
 * - On /korziny-cvetov/: ONLY baskets
 * - On /: all bouquets or filtered by interactive category chip
 */
export function filterBouquetsForRoute(
  bouquets: Bouquet[],
  route: SeoRoute,
  interactiveCategory: string = 'Все'
): Bouquet[] {
  // 1. Root main catalog route ('/')
  if (route.path === '/') {
    if (interactiveCategory === 'Все') return bouquets;
    return bouquets.filter((b) => b.category === interactiveCategory);
  }

  // 2. Strict tag-based routes
  if (route.targetTag) {
    const tag = route.targetTag.toLowerCase();
    return bouquets.filter((b) => {
      if (b.flowerTypes && b.flowerTypes.some((ft) => ft.toLowerCase().includes(tag))) return true;
      if (b.tags && b.tags.some((t) => t.toLowerCase().includes(tag))) return true;
      if (tag === 'розы' && /роз/i.test(b.title)) return true;
      if (tag === 'пионы' && /пион/i.test(b.title)) return true;
      if (tag === 'хризантемы' && /хризантем/i.test(b.title)) return true;
      if (tag === 'свадебные' && /свадебн/i.test(b.title)) return true;
      return false;
    });
  }

  // 3. Strict category-based routes
  if (route.targetCategory) {
    const cat = route.targetCategory.toLowerCase();
    return bouquets.filter((b) => {
      if (b.category.toLowerCase() === cat) return true;
      if (b.tags && b.tags.some((t) => t.toLowerCase() === cat)) return true;
      return false;
    });
  }

  return bouquets;
}

/**
 * Russian grammar pluralization:
 * 1 букет, 2-4 букета, 5+ букетов
 */
export function formatBouquetCount(count: number): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) {
    return `${count} букет`;
  }
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) {
    return `${count} букета`;
  }
  return `${count} букетов`;
}

export function formatShownCount(count: number): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  const word = formatBouquetCount(count);
  if (mod10 === 1 && mod100 !== 11) {
    return `Показан ${word}`;
  }
  return `Показано ${word}`;
}
